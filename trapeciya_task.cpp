#include <iostream>
#include <cmath>
using namespace std;

int main() {
    double a, b, c, d, h;
    double perimeter, area, midline;
    
    cout << "Программа для вычисления параметров трапеции\n";
    cout << "============================================\n\n";
    
    cout << "Введите длину верхнего основания (a): ";
    cin >> a;
    
    cout << "Введите длину нижнего основания (b): ";
    cin >> b;
    
    cout << "Введите длину левой боковой стороны (c): ";
    cin >> c;
    
    cout << "Введите длину правой боковой стороны (d): ";
    cin >> d;
    
    cout << "Введите высоту трапеции (h): ";
    cin >> h;
    
    // Вычисления
    perimeter = a + b + c + d;              // Периметр
    area = (a + b) / 2 * h;                  // Площадь
    midline = (a + b) / 2;                    // Средняя линия
    
    cout << "\nРезультаты вычислений:\n";
    cout << "----------------------------------------\n";
    cout << "Верхнее основание (a): " << a << endl;
    cout << "Нижнее основание (b): " << b << endl;
    cout << "Левая сторона (c): " << c << endl;
    cout << "Правая сторона (d): " << d << endl;
    cout << "Высота (h): " << h << endl;
    cout << "----------------------------------------\n";
    cout << "Периметр: " << perimeter << endl;
    cout << "Площадь: " << area << endl;
    cout << "Средняя линия: " << midline << endl;
    cout << "----------------------------------------\n";
    
    return 0;
}
